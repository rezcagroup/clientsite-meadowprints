def facts_html():
    rows = "".join(f'\n        <div class="fact"><dt>{k}</dt><dd>{v}</dd></div>' for k, v in FACTS)
    return f"""<!-- facts:start (generated by tools/ai_pages.py) -->
<section class="section-sm" id="at-a-glance">
  <div class="container" style="max-width:980px">
    <div class="center" style="margin-bottom:24px"><span class="eyebrow">At a glance</span><h2 class="mb0">Meadow Prints &amp; Embroidery, in short</h2></div>
    <dl class="facts">{rows}
    </dl>
  </div>
</section>
<!-- facts:end -->"""


def fill_facts(root):
    block = facts_html()
    for name in ("index.html", "about.html"):
        f = root / name
        s = f.read_text()
        s2, n = re.subn(r"<!-- facts:start.*?<!-- facts:end -->", lambda m: block, s, count=1, flags=re.S)
        assert n == 1, f"{name} has no facts markers"
        f.write_text(s2)


def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", s))).strip()


def page_summary(B, path):
    s = (B.ROOT / path).read_text()
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", s, re.S)
    lead = re.search(r'<p class="lead"[^>]*>(.*?)</p>', s, re.S)
    faqs = re.findall(r'<button class="acc-head">(.*?)<span class="chev">.*?<div class="acc-body-inner">(.*?)</div></div></div>', s, re.S)
    out = [f"### [{text(h1.group(1)) if h1 else path}]({B.url(path)})", ""]
    if lead:
        out += [text(lead.group(1)), ""]
    for q, a in faqs:
        out += [f"**{text(q)}**", text(a), ""]
    return "\n".join(out)


def build_llms_full(B, sections):
    parts = [(B.ROOT / "llms.txt").read_text().rstrip(), "", "---", "",
             "# Full details", "",
             "Below is the main content of the site's key pages, for AI assistants that want the complete picture.", ""]
    for heading, paths in sections:
        parts += [f"## {heading}", ""]
        parts += [page_summary(B, p) for p in paths]
    (B.ROOT / "llms-full.txt").write_text("\n".join(parts).rstrip() + "\n")


def write_indexnow_key(root):
    (root / f"{INDEXNOW_KEY}.txt").write_text(INDEXNOW_KEY)
